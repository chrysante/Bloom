#ifndef BLOOM_GRAPHICS_MATERIAL_MATERIALSOURCEDATA_H
#define BLOOM_GRAPHICS_MATERIAL_MATERIALSOURCEDATA_H

#include <string>
#include <vector>

#include <utl/hashtable.hpp>
#include <vml/vml.hpp>

#include "Bloom/Asset/Asset.h"
#include "Bloom/Asset/Serialization.h"
#include "Bloom/Core/Yaml.h"
#include "Bloom/GPU/Fwd.h"
#include "Bloom/Graphics/Material/Fwd.h"
#include "Bloom/Graphics/Material/MaterialSourceData.h"

namespace bloom {

/// Parameter to be set be a material instance
struct MaterialPrimitiveParameter {
    MaterialDataType type;
    uint32_t bufferOffset;
    std::string name;
    vml::float4 value;
};

/// Parameter to be set be a material instance
struct MaterialTextureParameter {
    static constexpr int UnusedBindingPoint = -1;

    bool hasFragmentBinding() const {
        return fragmentBindingPoint != UnusedBindingPoint;
    }
    bool hasVertexBinding() const {
        return vertexBindingPoint != UnusedBindingPoint;
    }

    MaterialDataType type;
    int fragmentBindingPoint = UnusedBindingPoint;
    int vertexBindingPoint = UnusedBindingPoint;
    std::string name;
    AssetHandle value;
};

/// Data generated by the material generator
struct MaterialSourceData {
    /// Shader source to be passed to the renderering APIs shader compiler
    std::string source;
    utl::hashmap<int, AssetHandle> constantFragmentTextures;
    std::vector<MaterialPrimitiveParameter> primitiveParameters;
    std::vector<MaterialTextureParameter> textureParameters;
    size_t parameterBufferSize;
    TriangleCullMode cullMode{};
};

} // namespace bloom

#ifndef BLOOM_NO_SERIALIZATION

BLOOM_MAKE_TEXT_SERIALIZER(bloom::MaterialPrimitiveParameter, type,
                           bufferOffset, name, value);

BLOOM_MAKE_TEXT_SERIALIZER(bloom::MaterialTextureParameter, type,
                           fragmentBindingPoint, vertexBindingPoint, name,
                           value);

#endif // BLOOM_NO_SERIALIZATION

#endif // BLOOM_GRAPHICS_MATERIAL_MATERIALSOURCEDATA_H
